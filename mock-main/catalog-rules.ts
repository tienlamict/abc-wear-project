/** Main System's product rules (spec §9.5), shared by the seed generator and the admin API. */

/** Known colors and the code used in SKUs; other colors get a code derived from the name. */
export const COLOR_CODES: Record<string, string> = {
  Đen: "DEN",
  Trắng: "TRANG",
  Xám: "XAM",
  "Xanh navy": "NAVY",
  Be: "BE",
  "Đỏ đô": "DO",
  "Xanh rêu": "REU",
  "Hồng pastel": "HONG",
};

export const SIZES = ["XS", "S", "M", "L", "XL", "XXL"] as const;

/** `P` + 6 digits, e.g. 1 → P000001. */
export function productIdFor(n: number): string {
  return `P${String(n).padStart(6, "0")}`;
}

/** Next free product id: one above the highest `P000123`-style id in use. */
export function nextProductId(ids: Iterable<string>): string {
  let max = 0;
  for (const id of ids) {
    const match = /^P(\d{6})$/.exec(id);
    if (match) max = Math.max(max, Number(match[1]));
  }
  return productIdFor(max + 1);
}

/** "Xanh rêu" → "REU" (known color) or e.g. "Vàng chanh" → "VANGCHANH". */
export function colorCode(color: string): string {
  const known = COLOR_CODES[color.trim()];
  if (known) return known;
  return color
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[đĐ]/g, "D")
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "")
    .slice(0, 16);
}

/** Suggested SKU `{productId}-{size}-{color code}`. */
export function suggestSku(productId: string, size: string, color: string): string {
  return `${productId}-${size.trim().toUpperCase()}-${colorCode(color)}`;
}

/** Object keys are generated by the server, never taken from the uploaded file name. */
export const imageKey = (productId: string, imageId: string) =>
  `products/${productId}/${imageId}.webp`;

export const seedImageKey = (productId: string, n: number) => imageKey(productId, `seed-${n}`);

/** `products/P000001/<imageId>.webp` → `<imageId>` (a uuid, or `seed-1` for seed images). */
export function imageIdOf(key: string): string {
  return key.slice(key.lastIndexOf("/") + 1).replace(/\.webp$/, "");
}

/** Lowercase, accents stripped: for accent-insensitive search in the admin list. */
export function fold(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[đĐ]/g, "d")
    .toLowerCase();
}
